async def classify(mon: MessageMonitor, text: str) -> Dict:
    return await mon._hybrid_classify_message(text)


def niches_of(result: Dict) -> Set[str]:
    if result.get("is_spam"):
        return set()
    return set(result.get("niches") or [])


async def run() -> int:
    mon = MessageMonitor(_Dummy(), _Dummy(), None)
    failed = 0
    total = 0

    print("=== POSITIVE ===")
    for text, need, forbid in POSITIVE:
        total += 1
        result = await classify(mon, text)
        got = niches_of(result)
        ok = need in got and not (got & forbid)
        status = "OK" if ok else "FAIL"
        if not ok:
            failed += 1
        print(f"[{status}] need={need!r} got={sorted(got)} | {text[:70]}")
        if not ok:
            print(f"       forbid_hit={sorted(got & forbid)} spam={result.get('is_spam')} type={result.get('message_type')} reason={result.get('reason')}")

    print("\n=== NEGATIVE / PRECISION ===")
    for text, forbid in NEGATIVES:
        total += 1
        result = await classify(mon, text)
        got = niches_of(result)
        # пустой forbid → вообще не должно быть ниш; иначе не должно быть пересечения
        ok = (not got) if not forbid else not (got & forbid)
        status = "OK" if ok else "FAIL"
        if not ok:
            failed += 1
        print(f"[{status}] forbid={sorted(forbid) or ['<any>']} got={sorted(got)} | {text[:70]}")

    print(f"\nTOTAL {total - failed}/{total} passed, {failed} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(asyncio.get_event_loop().run_until_complete(run()))
