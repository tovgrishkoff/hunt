def get_available_topics() -> List[str]:
    """
    Получить список доступных тем для мониторинга
    """
    return list(MONITORING_TOPICS.keys())

def get_topic_description(topic: str) -> str:
    """
    Получить описание темы
    """
    topic = topic.lower()
    for key, data in MONITORING_TOPICS.items():
        if topic in key or key in topic:
            return data["description"]
    return "Общий мониторинг чатов и каналов по выбранной теме"

def get_topic_keywords(topic: str) -> List[str]:
    """
    Получить ключевые слова для темы
    """
    topic = topic.lower()
    for key, data in MONITORING_TOPICS.items():
        if topic in key or key in topic:
            return data["keywords"]
    return []

